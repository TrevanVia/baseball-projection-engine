// The season being projected. Bump once a year (after the World Series).
// Backtests set it to a past season via setProjSeason().
export let PROJ_SEASON = 2027;
export function setProjSeason(y) { PROJ_SEASON = y; }

// Age during the projected season (age on July 1), from an MLB API person.
// Falls back to currentAge when no birth date is present.
export function projAge(person) {
  const bd = person?.birthDate;
  if (!bd) return person?.currentAge;
  const [y, m, d] = bd.split("-").map(Number);
  return PROJ_SEASON - y - ((m > 7 || (m === 7 && d > 1)) ? 1 : 0);
}

