// Lookup: given a value and a percentile table, return the percentile (0-100).
// `higher` = true means higher values are better (e.g. velo, whiff).
// `higher` = false means lower values are better (e.g. xERA, xwOBA against).
export function pctlLookup(val, table, higher) {
  if (val == null || !table) return 50;
  // Find which bucket the value falls into (each bucket = 5 percentile points)
  for (let i = 0; i < table.length - 1; i++) {
    if (val <= table[i + 1]) {
      const frac = (val - table[i]) / (table[i + 1] - table[i] || 1);
      const raw = (i + frac) * 5; // each index = 5 percentile points
      return higher
        ? Math.max(1, Math.min(99, Math.round(raw)))
        : Math.max(1, Math.min(99, Math.round(100 - raw)));
    }
  }
  return higher ? 99 : 1;
}

